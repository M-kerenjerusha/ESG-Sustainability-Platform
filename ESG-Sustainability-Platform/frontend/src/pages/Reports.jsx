import { useEffect, useState } from "react";
import DashboardLayout from "../layouts/DashboardLayout";
import Modal from "../components/Modal";
import ConfirmDialog from "../components/ConfirmDialog";
import { useToast } from "../context/ToastContext";
import api, { getErrorMessage } from "../services/api";

const emptyForm = { title: "", periodType: "monthly", periodStart: "", periodEnd: "" };

const Reports = () => {
  const { showToast } = useToast();
  const [reports, setReports] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [showForm, setShowForm] = useState(false);
  const [form, setForm] = useState(emptyForm);
  const [saving, setSaving] = useState(false);
  const [deleteTarget, setDeleteTarget] = useState(null);
  const [deleting, setDeleting] = useState(false);

  const loadReports = async () => {
    setLoading(true);
    setError("");
    try {
      const { data } = await api.get("/reports");
      setReports(data.data);
    } catch (e) {
      setError(getErrorMessage(e));
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => { loadReports(); }, []);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setSaving(true);
    try {
      await api.post("/reports", form);
      showToast("Report generated successfully");
      setShowForm(false);
      setForm(emptyForm);
      loadReports();
    } catch (e) {
      showToast(getErrorMessage(e), "error");
    } finally {
      setSaving(false);
    }
  };

  const handleDelete = async () => {
    if (!deleteTarget) return;
    setDeleting(true);
    try {
      await api.delete(`/reports/${deleteTarget._id}`);
      showToast("Report snapshot deleted");
      setDeleteTarget(null);
      loadReports();
    } catch (e) {
      showToast(getErrorMessage(e), "error");
    } finally {
      setDeleting(false);
    }
  };

  const handleDownload = async (report) => {
    try {
      const response = await api.get(`/reports/${report._id}/pdf`, { responseType: "blob" });
      const url = window.URL.createObjectURL(new Blob([response.data], { type: "application/pdf" }));
      const link = document.createElement("a");
      link.href = url;
      link.setAttribute("download", `${report.title.replace(/\s+/g, "_")}.pdf`);
      document.body.appendChild(link);
      link.click();
      link.remove();
    } catch (e) {
      showToast("Failed to download PDF report", "error");
    }
  };

  return (
    <DashboardLayout title="Sustainability Reports">
      <div className="flex-between mb-16">
        <div className="text-muted">Generate a snapshot ESG report for a given period and download it as PDF.</div>
        <button className="btn btn-primary" onClick={() => setShowForm(true)}>+ Generate Report</button>
      </div>

      {error && <div className="error-banner">{error}</div>}
      {loading ? (
        <div className="loading-state">Loading reports...</div>
      ) : reports.length === 0 ? (
        <div className="card empty-state">No reports generated yet.</div>
      ) : (
        <div className="card table-wrap">
          <table>
            <thead>
              <tr><th>Title</th><th>Period Type</th><th>Start</th><th>End</th><th>Overall Score</th><th>Generated By</th><th>Actions</th></tr>
            </thead>
            <tbody>
              {reports.map((r) => (
                <tr key={r._id}>
                  <td>{r.title}</td>
                  <td style={{ textTransform: "capitalize" }}>{r.periodType}</td>
                  <td>{new Date(r.periodStart).toLocaleDateString()}</td>
                  <td>{new Date(r.periodEnd).toLocaleDateString()}</td>
                  <td>{r.snapshot?.esgScore?.overallScore ?? "-"}</td>
                  <td>{r.generatedBy?.name || "-"}</td>
                  <td>
                    <button className="btn btn-primary btn-sm" onClick={() => handleDownload(r)}>Download PDF</button>{" "}
                    <button className="btn btn-danger btn-sm" onClick={() => setDeleteTarget(r)}>Delete</button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {showForm && (
        <Modal title="Generate Sustainability Report" onClose={() => setShowForm(false)}>
          <form onSubmit={handleSubmit}>
            <div className="form-group">
              <label className="form-label">Report Title</label>
              <input className="form-input" required value={form.title} onChange={(e) => setForm({ ...form, title: e.target.value })} placeholder="e.g. September 2026 ESG Report" />
            </div>
            <div className="form-group">
              <label className="form-label">Period Type</label>
              <select className="form-select" value={form.periodType} onChange={(e) => setForm({ ...form, periodType: e.target.value })}>
                <option value="monthly">Monthly</option>
                <option value="yearly">Yearly</option>
              </select>
            </div>
            <div className="form-row">
              <div className="form-group">
                <label className="form-label">Period Start</label>
                <input type="date" className="form-input" required value={form.periodStart} onChange={(e) => setForm({ ...form, periodStart: e.target.value })} />
              </div>
              <div className="form-group">
                <label className="form-label">Period End</label>
                <input type="date" className="form-input" required value={form.periodEnd} onChange={(e) => setForm({ ...form, periodEnd: e.target.value })} />
              </div>
            </div>
            <div style={{ display: "flex", justifyContent: "flex-end", gap: 10, marginTop: 10 }}>
              <button type="button" className="btn btn-secondary" onClick={() => setShowForm(false)}>Cancel</button>
              <button type="submit" className="btn btn-primary" disabled={saving}>{saving ? "Generating..." : "Generate Report"}</button>
            </div>
          </form>
        </Modal>
      )}

      {deleteTarget && (
        <ConfirmDialog
          message={`Are you sure you want to delete the report snapshot "${deleteTarget.title}"?`}
          onConfirm={handleDelete}
          onCancel={() => setDeleteTarget(null)}
          loading={deleting}
        />
      )}
    </DashboardLayout>
  );
};

export default Reports;
